class CityEvent {
  final String id;
  final String title;
  final String description;
  final String location;
  final String startDate;
  final String endDate;

  CityEvent({
    required this.id,
    required this.title,
    required this.description,
    required this.location,
    required this.startDate,
    required this.endDate,
  });
}
